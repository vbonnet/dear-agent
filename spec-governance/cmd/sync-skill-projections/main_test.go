func TestSyncValidatesAllMetadataBeforeWriting(t *testing.T) {
	root := t.TempDir()
	writeCanonicalSkills(t, root)
	if err := sync(root, false); err != nil {
		t.Fatal(err)
	}
	target := filepath.Join(root, ".agents", "skills", "audit-specs", "SKILL.md")
	before, err := os.ReadFile(target)
	if err != nil {
		t.Fatal(err)
	}
	writeSkill(t, root, "audit-specs", "---\nname: audit-specs\ndescription: changed\n---\n")
	writeSkill(t, root, "write-spec", "---\nname: write-spec\ndescription: broken\n")
	if err := sync(root, false); err == nil || !strings.Contains(err.Error(), "closing YAML") {
		t.Fatalf("sync() error = %v, want invalid second skill", err)
	}
	after, err := os.ReadFile(target)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(before, after) {
		t.Fatal("first projection changed before all canonical metadata was validated")
	}
}

func TestSyncDiscoversNewAndObsoleteGeneratedSkills(t *testing.T) {
	root := t.TempDir()
	writeCanonicalSkills(t, root)
	writeSkill(t, root, "review-spec", "---\nname: review-spec\ndescription: Review a specification.\n---\n")
	if err := sync(root, false); err != nil {
		t.Fatal(err)
	}
	newProjection := filepath.Join(root, ".agents", "skills", "review-spec", "SKILL.md")
	if _, err := os.Stat(newProjection); err != nil {
		t.Fatalf("new canonical skill was not projected: %v", err)
	}
	if err := os.RemoveAll(filepath.Join(root, "spec-governance", "skills", "review-spec")); err != nil {
		t.Fatal(err)
	}
	if err := sync(root, true); err == nil || !strings.Contains(err.Error(), "obsolete") {
		t.Fatalf("sync(check) error = %v, want obsolete projection", err)
	}
	if err := sync(root, false); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(newProjection); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("obsolete generated projection still exists: %v", err)
	}
}

