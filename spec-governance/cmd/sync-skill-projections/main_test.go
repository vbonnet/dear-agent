func TestReadMetadataUsesStrictYAMLFrontmatter(t *testing.T) {
	tests := []struct {
		name    string
		content string
		wantErr string
	}{
		{name: "missing close", content: "---\nname: write-spec\ndescription: broken\n", wantErr: "closing YAML"},
		{name: "duplicate", content: "---\nname: write-spec\nname: other\ndescription: duplicate\n---\n", wantErr: "already defined"},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			if _, err := parseMetadata([]byte(test.content)); err == nil || !strings.Contains(err.Error(), test.wantErr) {
				t.Fatalf("readMetadata() error=%v, want %q", err, test.wantErr)
			}
		})
	}
	metadata, err := parseMetadata([]byte("---\nname: write-spec\ndescription: >-\n  Write a neutral\n  specification.\n---\n"))
	if err != nil || metadata.description != "Write a neutral specification." {
		t.Fatalf("folded metadata=%#v err=%v", metadata, err)
	}
}

func TestSyncRejectsInvalidPackageMetadataBeforeWriting(t *testing.T) {
	tests := []struct {
		name    string
		mutate  func(*testing.T, string)
		wantErr string
	}{
		{
			name: "plugin skill export",
			mutate: func(t *testing.T, root string) {
				writeFile(t, root, "spec-governance/.claude-plugin/plugin.json", `{"name":"spec-governance","version":"0.1.0","description":"test","author":{"name":"test"},"skills":["./other/"]}`)
			},
			wantErr: "skills must be exactly",
		},
		{
			name: "plugin unknown field",
			mutate: func(t *testing.T, root string) {
				writeFile(t, root, "spec-governance/.claude-plugin/plugin.json", `{"name":"spec-governance","version":"0.1.0","description":"test","author":{"name":"test"},"skills":["./skills/"],"unexpected":true}`)
			},
			wantErr: "unknown field",
		},
		{
			name: "plugin invalid version",
			mutate: func(t *testing.T, root string) {
				writeFile(t, root, "spec-governance/.claude-plugin/plugin.json", `{"name":"spec-governance","version":"latest","description":"test","author":{"name":"test"},"skills":["./skills/"]}`)
			},
			wantErr: "identity, version, description, and author",
		},
		{
			name: "OpenAI prompt delegates to another skill",
			mutate: func(t *testing.T, root string) {
				writeFile(t, root, "spec-governance/skills/write-spec/agents/openai.yaml", "interface:\n  display_name: Write SPEC\n  short_description: Write a SPEC\n  default_prompt: Use $audit-specs instead.\n")
			},
			wantErr: "must delegate through $write-spec",
		},
		{
			name: "OpenAI prompt uses a longer near-prefix skill name",
			mutate: func(t *testing.T, root string) {
				writeFile(t, root, "spec-governance/skills/write-spec/agents/openai.yaml", "interface:\n  display_name: Write SPEC\n  short_description: Write a SPEC\n  default_prompt: Use $write-specification instead.\n")
			},
			wantErr: "must delegate through $write-spec",
		},
		{
			name: "OpenAI metadata unknown field",
			mutate: func(t *testing.T, root string) {
				writeFile(t, root, "spec-governance/skills/write-spec/agents/openai.yaml", "interface:\n  display_name: Write SPEC\n  short_description: Write a SPEC\n  default_prompt: Use $write-spec.\n  unexpected: true\n")
			},
			wantErr: "field unexpected not found",
		},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			root := t.TempDir()
			writeCanonicalSkills(t, root)
			test.mutate(t, root)
			if err := sync(root, false); err == nil || !strings.Contains(err.Error(), test.wantErr) {
				t.Fatalf("sync() error = %v, want %q", err, test.wantErr)
			}
			if _, err := os.Stat(filepath.Join(root, ".agents", "skills", "write-spec", "SKILL.md")); !errors.Is(err, os.ErrNotExist) {
				t.Fatalf("projection was written before package metadata validation: %v", err)
			}
		})
	}
}

func writeCanonicalSkills(t *testing.T, root string) {
	t.Helper()
	writeFile(t, root, "spec-governance/.claude-plugin/plugin.json", `{"name":"spec-governance","version":"0.1.0","description":"Test SPEC governance plugin","author":{"name":"test"},"skills":["./skills/"]}`)
	for _, name := range testSkillNames {
		writeSkill(t, root, name, "---\nname: "+name+"\ndescription: \"Use "+name+" for canonical SPEC governance.\"\n---\n")
	}
}

func writeSkill(t *testing.T, root, name, content string) {
	t.Helper()
	writeFile(t, root, filepath.Join("spec-governance", "skills", name, "SKILL.md"), content)
	writeFile(t, root, filepath.Join("spec-governance", "skills", name, "agents", "openai.yaml"), "interface:\n  display_name: Test skill\n  short_description: Test canonical skill\n  default_prompt: Use $"+name+" for this request.\n")
}

func writeFile(t *testing.T, root, relative, content string) {
	t.Helper()
	path := filepath.Join(root, relative)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}
