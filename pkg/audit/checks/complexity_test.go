// writeGo writes src to dir/name. It is a tiny helper: tests in this
// package usually inline file content but we have a few callers here.
func writeGo(t *testing.T, dir, name, src string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, name), []byte(src), 0o644); err != nil {
		t.Fatalf("write %s: %v", name, err)
	}
}
